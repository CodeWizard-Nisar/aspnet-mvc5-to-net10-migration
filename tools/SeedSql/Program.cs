using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using ConfReg.Data.Seed;
using ConfReg.Domain.Entities;

// Fixed "now" for the seed. Everything in the data is relative to this, so it never changes.
var anchor = new DateTime(2026, 11, 20, 12, 0, 0, DateTimeKind.Utc);

// Same AES key/IV as Legacy.Web/Web.config (made-up demo values). The tests seed LEGACY-format password
// ciphertext on purpose: after Phase 3 the app must still log these users in, then re-hash them.
string Encrypt(string plain)
{
    using var aes = Aes.Create();
    aes.Key = Encoding.ASCII.GetBytes("confreg-demo-key-NOT-A-SECRET-00");
    aes.IV = Encoding.ASCII.GetBytes("confreg-demo-iv!");
    var bytes = Encoding.UTF8.GetBytes(plain);
    return Convert.ToBase64String(aes.CreateEncryptor().TransformFinalBlock(bytes, 0, bytes.Length));
}

var plan = SeedPlan.Build(anchor, Encrypt, out var admins, out var settings);
// A wide, fixed registration window, so the wizard is "open" no matter what today's date is.
foreach (var s in settings)
{
    if (s.Key == "Registration.OpensUtc") s.Value = new DateTime(2000, 1, 1, 0, 0, 0, DateTimeKind.Utc).ToString("o");
    if (s.Key == "Registration.ClosesUtc") s.Value = new DateTime(2100, 1, 1, 0, 0, 0, DateTimeKind.Utc).ToString("o");
}

string Q(string v) => v == null ? "NULL" : "N'" + v.Replace("'", "''") + "'";
string D(DateTime? d) => d == null ? "NULL" : "'" + d.Value.ToString("yyyy-MM-ddTHH:mm:ss.fff", CultureInfo.InvariantCulture) + "'";
string M(decimal m) => m.ToString("0.00", CultureInfo.InvariantCulture);

var sb = new StringBuilder();
sb.AppendLine("-- GENERATED by tools/SeedSql from SeedPlan with a fixed clock (" + anchor.ToString("o") + "). Do not edit by hand.");
sb.AppendLine("-- Wipes every ConfReg table and reloads the same rows, with the same ids, every time.");
sb.AppendLine("DELETE FROM Payments; DELETE FROM RegistrationTalks; DELETE FROM Registrations; DELETE FROM Attendees; DELETE FROM Talks; DELETE FROM AdminUsers; DELETE FROM Settings;");

void Table(string name, string cols, IEnumerable<string> rows, int? maxId)
{
    var list = rows.ToList();
    if (maxId.HasValue) sb.AppendLine($"SET IDENTITY_INSERT {name} ON;");
    foreach (var r in list) sb.AppendLine($"INSERT INTO {name} ({cols}) VALUES ({r});");
    if (maxId.HasValue) sb.AppendLine($"SET IDENTITY_INSERT {name} OFF; DBCC CHECKIDENT ('{name}', RESEED, {maxId.Value}) WITH NO_INFOMSGS;");
}

Table("Talks", "Id,Title,Speaker,Track,StartsUtc,DurationMinutes,Room,Capacity",
    plan.Talks.Select(t => $"{t.Id},{Q(t.Title)},{Q(t.Speaker)},{Q(t.Track)},{D(t.StartsUtc)},{t.DurationMinutes},{Q(t.Room)},{t.Capacity}"), plan.Talks.Max(t => t.Id));
Table("Attendees", "Id,FirstName,LastName,Email,Company,JobTitle,DietaryRequirements,CreatedUtc",
    plan.Attendees.Select(a => $"{a.Id},{Q(a.FirstName)},{Q(a.LastName)},{Q(a.Email)},{Q(a.Company)},{Q(a.JobTitle)},{Q(a.DietaryRequirements)},{D(a.CreatedUtc)}"), plan.Attendees.Max(a => a.Id));
Table("Registrations", "Id,ReferenceCode,AttendeeId,TicketType,Status,TotalAmount,CreatedUtc,ConfirmedUtc,ConfirmationSentUtc",
    plan.Registrations.Select(r => $"{r.Id},{Q(r.ReferenceCode)},{r.AttendeeId},{(int)r.TicketType},{(int)r.Status},{M(r.TotalAmount)},{D(r.CreatedUtc)},{D(r.ConfirmedUtc)},{D(r.ConfirmationSentUtc)}"), plan.Registrations.Max(r => r.Id));
Table("RegistrationTalks", "RegistrationId,TalkId",
    plan.Registrations.SelectMany(r => r.RegistrationTalks.Select(rt => $"{r.Id},{rt.TalkId}")), null);
Table("Payments", "Id,RegistrationId,Amount,Provider,ProviderRef,Status,ProcessedUtc",
    plan.Payments.Select(p => $"{p.Id},{p.RegistrationId},{M(p.Amount)},{Q(p.Provider)},{Q(p.ProviderRef)},{(int)p.Status},{D(p.ProcessedUtc)}"), plan.Payments.Max(p => p.Id));
int aid = 0;
Table("AdminUsers", "Id,Email,PasswordHash,Role", admins.Select(a => $"{++aid},{Q(a.Email)},{Q(a.PasswordHash)},{Q(a.Role)}"), admins.Count);
Table("Settings", "[Key],[Value]", settings.Select(s => $"{Q(s.Key)},{Q(s.Value)}"), null);

var outPath = args.Length > 0 ? args[0] : Path.Combine("tests", "Characterization", "Data", "seed.sql");
File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"wrote {outPath}: {plan.Attendees.Count} attendees, {plan.Talks.Count} talks, {plan.Registrations.Count} registrations, {plan.Payments.Count} payments");
